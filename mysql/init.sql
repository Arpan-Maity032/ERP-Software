CREATE DATABASE IF NOT EXISTS USER_DB;
CREATE DATABASE IF NOT EXISTS MASTER_DB;
CREATE DATABASE IF NOT EXISTS STORE_DB;

CREATE USER IF NOT EXISTS 'user_app'@'%' IDENTIFIED BY '#UsersPassword_123!';
CREATE USER IF NOT EXISTS 'master_app'@'%' IDENTIFIED BY '#MasterPassword_123$';
CREATE USER IF NOT EXISTS 'store_app'@'%' IDENTIFIED BY '#StorePassword_123$';

GRANT ALL PRIVILEGES ON USER_DB.* TO 'user_app'@'%';
GRANT ALL PRIVILEGES ON MASTER_DB.* TO 'master_app'@'%';
GRANT ALL PRIVILEGES ON STORE_DB.* TO 'store_app'@'%';